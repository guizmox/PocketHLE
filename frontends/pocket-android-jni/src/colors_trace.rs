pub fn install(emu: &mut Emulator, image: &pocket_core::pe::LoadedImage) {
    // Process metadata drops section bytes after mapping; use the retained PE image.
    let matches = {
        image.image_base == 0x10000
            && SIGNATURES.iter().all(|(va, expected)| {
                image
                    .sections
                    .iter()
                    .filter(|section| section.is_executable())
                    .any(|section| {
                        va.checked_sub(image.image_base + section.virtual_address)
                            .and_then(|offset| {
                                section
                                    .data
                                    .get(offset as usize..offset as usize + expected.len())
                            })
                            .is_some_and(|bytes| bytes == *expected)
                    })
            })
    };
    if !matches {
        return;
    }
    for (va, label) in [
        (0xdd930, "Colors post-registration TWPlayerValid-result"),
        (0xdd948, "Colors local-validation TW_UNKNOWN_ERROR"),
        (0xde254, "Colors network-error branch"),
        (0xde2e8, "Colors network TW_TRANSFER_ERROR"),
        (0x18328, "Colors registration save-XML root"),
        (0x1836c, "Colors registration SaveFile-read-return"),
        (0x18340, "Colors registration SaveFile filename-check"),
        (0x1839c, "Colors registration Character-node-result"),
        (0x18418, "Colors registration SaveFile-write-return"),
        (0x18460, "Colors registration config-save-call"),
        (0x1850c, "Colors TWPlayerValid parsed-value"),
        (0xdd974, "Colors local TWPlayerValid-result"),
        (0xdd984, "Colors local profile reset"),
        (0xdd998, "Colors local profile valid"),
        (0xe6b9c, "Colors getuserinfo XML-result"),
        (0xe6bec, "Colors getuserinfo profile-result"),
        (0xe6d38, "Colors setuserinfo XML-result"),
        (0xe6d90, "Colors setuserinfo profile-result"),
        (0xe6db0, "Colors setuserinfo rejected"),
        (0xe6df4, "Colors setuserinfo marking-TWPlayerValid"),
        (0xe6e10, "Colors setuserinfo accepted"),
        (0xf4860, "Colors HTTP-object ready-result"),
        (0xf4870, "Colors HTTP-object response-pointer"),
        (0xf48c4, "Colors XML-parser completed"),
    ] {
        if let Err(error) = emu.add_register_trace(va, label) {
            log::warn!("Colors registration trace unavailable: {error}");
            return;
        }
    }
    log::warn!("Colors registration ARM diagnostics active (matched callback/parser signatures)");
}
